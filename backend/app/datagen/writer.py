def _parse(col, text: str):
    if text == "":
        return None if col.nullable else ""
    t = col.type
    if isinstance(t, Boolean):
        return text == "true"
    if isinstance(t, Date):
        return date.fromisoformat(text)
    if isinstance(t, (BigInteger, Integer, SmallInteger)):
        return int(text)
    if isinstance(t, Numeric):
        return Decimal(text)
    return text


def _open(out: Path, rel: str) -> io.TextIOWrapper:
    path = out / rel
    if path.exists():
        return open(path, encoding="utf-8", newline="")
    return io.TextIOWrapper(gzip.open(str(path) + ".gz", "rb"), encoding="utf-8", newline="")


def read_table(out: Path, name: str, rel: str | None = None) -> list[dict]:
    cols = [c for c in schema.TABLES[name].columns]
    with _open(out, rel or f"{name}.csv") as f:
        reader = csv.reader(f)
        header = next(reader)
        if header != [c.name for c in cols]:
            raise ValueError(f"{name}: header {header} does not match the schema")
        return [{c.name: _parse(c, v) for c, v in zip(cols, row, strict=True)} for row in reader]


def read(out: Path) -> tuple[Dataset, list[dict]]:
    ds = {name: read_table(out, name) for name in schema.DATA_TABLES}
    return ds, read_table(out, GT, "ground_truth/ground_truth.csv")
