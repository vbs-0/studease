"""Exports: CSV, JSON and SQL seed, plus a manifest with row counts and SHA-256 checksums.

Output is byte-stable: rows are sorted by primary key, columns follow schema order, newlines are `\\n`, text is
UTF-8. The checksum is taken over the uncompressed bytes, so it does not depend on the zlib version.
"""
from __future__ import annotations

import csv
import gzip
import hashlib
import io
import json
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

from sqlalchemy import BigInteger, Boolean, Date, Integer, Numeric, SmallInteger

from app import schema
from app.domain.calendar import AS_OF

Dataset = dict[str, list[dict]]
GT = "ground_truth"
NO_EXTERNAL_DATA = ("All data is synthetic and generated by this repository's generator from a fixed seed. "
                    "No external dataset, scraped source or real personal data is used.")


def cell(v) -> str:
    """One value as CSV text: empty for NULL, lowercase true/false, ISO dates."""
    if v is None:
        return ""
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, (date, datetime)):
        return v.isoformat()
    return str(v)


def _pk(name: str) -> list[str]:
    return [c.name for c in schema.TABLES[name].primary_key.columns]


def ordered(name: str, rows: list[dict]) -> list[dict]:
    key = _pk(name)
    return sorted(rows, key=lambda r: tuple(r[k] for k in key))


def csv_bytes(name: str, rows: list[dict]) -> bytes:
    cols = schema.columns(name)
    buf = io.StringIO(newline="")
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(cols)
    for row in ordered(name, rows):
        w.writerow([cell(row[c]) for c in cols])
    return buf.getvalue().encode("utf-8")


def _json_default(v):
    if isinstance(v, (date, datetime)):
        return v.isoformat()
    if isinstance(v, Decimal):
        return str(v)
    raise TypeError(type(v))


def json_bytes(name: str, rows: list[dict]) -> bytes:
    cols = schema.columns(name)
    body = [{c: row[c] for c in cols} for row in ordered(name, rows)]
    return (json.dumps(body, ensure_ascii=False, default=_json_default, separators=(",", ":")) + "\n").encode()


def sql_value(v) -> str:
    if v is None:
        return "NULL"
    if v is True:
        return "TRUE"
    if v is False:
        return "FALSE"
    if isinstance(v, (date, datetime)):
        return f"'{v.isoformat()}'"
    if isinstance(v, (int, Decimal)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def sql_text(name: str, rows: list[dict], batch: int = 500) -> str:
    cols = schema.columns(name)
    table = schema.TABLES[name]
    target = f"{table.schema}.{table.name}" if table.schema else table.name
    out = []
    rows = ordered(name, rows)
    for i in range(0, len(rows), batch):
        values = ",\n".join("(" + ", ".join(sql_value(r[c]) for c in cols) + ")" for r in rows[i:i + batch])
        out.append(f"INSERT INTO {target} ({', '.join(cols)}) VALUES\n{values};\n")
    return "".join(out)


def fingerprint(ds: Dataset, gt: list[dict]) -> dict:
    """Row counts and SHA-256 per table, without touching the disk. The manifest is built from this."""
    tables = {}
    for name in [*schema.DATA_TABLES, GT]:
        raw = csv_bytes(name, gt if name == GT else ds[name])
        tables[name] = {"rows": len(gt if name == GT else ds[name]), "sha256": hashlib.sha256(raw).hexdigest(),
                        "bytes": len(raw)}
    return tables


def manifest(ds: Dataset, gt: list[dict], scale: str, seed: int, files: list[str]) -> dict:
    tables = fingerprint(ds, gt)
    return {"project": "studease", "scale": scale, "seed": seed, "as_of": AS_OF.isoformat(),
            "command": f"python -m app.cli generate --scale {scale} --seed {seed}",
            "external_data": {"used": False, "note": NO_EXTERNAL_DATA},
            "checksum": "SHA-256 over the uncompressed CSV bytes of each table",
            "totals": {"rows": sum(t["rows"] for n, t in tables.items() if n != GT),
                       "ground_truth_rows": tables[GT]["rows"]},
            "tables": {n: t for n, t in tables.items() if n != GT}, "ground_truth": tables[GT],
            "files": sorted(files)}


def _put(path: Path, data: bytes, gz: bool) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    if gz:
        path = path.with_name(path.name + ".gz")
        with open(path, "wb") as raw, gzip.GzipFile(filename="", fileobj=raw, mode="wb", mtime=0,
                                                    compresslevel=9) as f:
            f.write(data)
    else:
        path.write_bytes(data)
    return path.name


def write(ds: Dataset, gt: list[dict], out: Path, scale: str, seed: int, formats: tuple[str, ...] = ("csv",),
          gz: bool = False, sql_dir: Path | None = None) -> dict:
    """Write inputs to `out`, ground truth to `out/ground_truth/`, the manifest to `out/manifest.json`."""
    files = []
    for name in schema.DATA_TABLES:
        if "csv" in formats:
            files.append(_put(out / f"{name}.csv", csv_bytes(name, ds[name]), gz))
        if "json" in formats:
            files.append(_put(out / "json" / f"{name}.json", json_bytes(name, ds[name]), gz))
    gdir = out / "ground_truth"
    files.append("ground_truth/" + _put(gdir / "ground_truth.csv", csv_bytes(GT, gt), gz))
    if "json" in formats:
        files.append("ground_truth/" + _put(gdir / "ground_truth.json", json_bytes(GT, gt), gz))
    if "sql" in formats and sql_dir is not None:
        header = f"-- StudEase seed data. scale={scale} seed={seed}. Load after `alembic upgrade head`.\n"
        sql_dir.mkdir(parents=True, exist_ok=True)
        (sql_dir / f"{scale}.sql").write_text(
            header + "BEGIN;\n" + "".join(sql_text(n, ds[n]) for n in schema.DATA_TABLES) + "COMMIT;\n",
            encoding="utf-8", newline="\n")
        (sql_dir / f"{scale}_ground_truth.sql").write_text(
            header + "-- ground truth: kept apart from the input seed on purpose\nBEGIN;\n"
            + sql_text(GT, gt) + "COMMIT;\n", encoding="utf-8", newline="\n")
    m = manifest(ds, gt, scale, seed, files)
    (out / "manifest.json").write_text(json.dumps(m, indent=2) + "\n", encoding="utf-8", newline="\n")
    return m


