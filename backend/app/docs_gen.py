"""Generated documentation: data dictionary, ER diagram and a worked example, all from the schema and the data.

Nothing here is typed by hand, so the documents cannot drift from the code. `python -m app.cli docs` writes them;
`python -m app.cli docs --check` fails if the committed copies are stale (a test runs it).
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from sqlalchemy import CheckConstraint, UniqueConstraint

from app import ids, schema
from app.domain import billing, ledger
from app.domain.status import TRANSITIONS
from app.money import inr

ROOT = Path(__file__).resolve().parents[2]
TYPE_NAMES = {"BigInteger": "bigint", "Integer": "integer", "SmallInteger": "smallint", "Boolean": "boolean",
              "Date": "date", "DateTime": "timestamp (UTC)", "JSONB": "json"}
ORDER = [*schema.DATA_TABLES, "ground_truth", *schema.OPERATIONAL_TABLES]
GENERATED = "<!-- Generated by `python -m app.cli docs` from backend/app/schema.py. Do not edit by hand. -->\n"


def type_name(t) -> str:
    n = t.__class__.__name__
    if n == "String":
        return f"string({t.length})"
    if n == "Numeric":
        return f"decimal({t.precision},{t.scale})"
    return TYPE_NAMES[n]


def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ") if text not in (None, "") else ""


def _uniqueness(table, col) -> str:
    pk = list(table.primary_key.columns)
    bits = []
    if col in pk:
        bits.append("primary key" if len(pk) == 1 else "part of primary key")
    if col.unique:
        bits.append("unique")
    for c in sorted((c for c in table.constraints if isinstance(c, UniqueConstraint)), key=lambda c: str(c.name)):
        if col.name in c.columns and len(c.columns) > 1:
            bits.append("unique with " + ", ".join(sorted(x.name for x in c.columns if x.name != col.name)))
    return "; ".join(bits)


def _row_counts() -> dict[str, dict[str, int]]:
    out = {}
    for scale in ("starter", "full"):
        path = ROOT / "data" / scale / "manifest.json"
        if path.exists():
            m = json.loads(path.read_text(encoding="utf-8"))
            out[scale] = {**{k: v["rows"] for k, v in m["tables"].items()}, "ground_truth": m["ground_truth"]["rows"]}
    return out


def _relationship(child, fk) -> str:
    col = fk.parent
    parent = fk.column.table.name
    one_to_one = col.unique or (col in list(child.primary_key.columns) and len(list(child.primary_key.columns)) == 1)
    kind = "1:0..1" if one_to_one else ("N:1 optional" if col.nullable else "N:1")
    return f"{child.name}.{col.name} -> {parent}.{fk.column.name} ({kind})"


def data_dictionary() -> str:
    counts = _row_counts()
    out = [GENERATED, "# Data dictionary\n",
           "Every table and field, generated from [`backend/app/schema.py`](../backend/app/schema.py). The same "
           "definitions create the database (Alembic), order the CSV columns, and drive the enum and required-field "
           "checks in validation.\n",
           "## Conventions\n",
           "- **Money** is an integer number of **paise** (1 INR = 100 paise), in `*_paise` columns (`bigint`). There "
           "is no floating-point money anywhere.",
           "- **Dates** are calendar dates (`YYYY-MM-DD`); the simulation is day-granular. Timestamps appear only in "
           "operational tables and are UTC.",
           "- **IDs** are immutable, zero-padded and carry their parents; the format of every primary key is in the "
           "table below and is checked by validation (check C1).",
           "- **Required / optional**: optional fields may be empty (`NULL`); everything else must be present.",
           "- **Allowed values** are enforced twice: by a `CHECK` constraint in the database and by validation "
           "(check C3).",
           "- **Ground truth** (`gt.ground_truth`) lives in its own schema and folder and is never joined into an "
           "input table.\n",
           "## Tables\n", "| Table | Purpose | Primary key format | Rows (starter) | Rows (full) |",
           "|---|---|---|---|---|"]
    for name in ORDER:
        t = schema.TABLES[name]
        pattern = ids.PATTERNS[name].pattern if name in ids.PATTERNS else "composite"
        purpose = t.comment.split(":", 1)[1].strip() if ":" in t.comment else t.comment
        out.append(f"| [`{name}`](#{name}) | {_cell(purpose)} | `{_cell(pattern)}` | "
                   f"{counts.get('starter', {}).get(name, '')} | {counts.get('full', {}).get(name, '')} |")
    out.append("")
    for name in ORDER:
        t = schema.TABLES[name]
        schema_note = f" (schema `{t.schema}`)" if t.schema else ""
        out += [f"## {name}", f"\n{_cell(t.comment)}{schema_note}\n"]
        fks = [_relationship(t, fk) for fk in sorted(t.foreign_keys, key=lambda f: f.parent.name)]
        if fks:
            out += ["**Relationships:** " + "; ".join(f"`{x}`" for x in fks) + "\n"]
        checks = sorted(str(c.sqltext) for c in t.constraints
                        if isinstance(c, CheckConstraint) and not str(c.name).endswith("_allowed"))
        if checks:
            out += ["**Table rules:** " + "; ".join(f"`{_cell(c)}`" for c in checks) + "\n"]
        out += ["| Field | Type | Required | Allowed values | Unit | Uniqueness | Validation rule | Description |",
                "|---|---|---|---|---|---|---|---|"]
        for c in t.columns:
            allowed = ", ".join(f"`{v}`" for v in c.info["allowed"]) if c.info.get("allowed") else ""
            out.append(f"| `{c.name}` | {type_name(c.type)} | {'optional' if c.nullable else 'required'} | {allowed} | "
                       f"{_cell(c.info.get('unit'))} | {_cell(_uniqueness(t, c))} | {_cell(c.info.get('rule'))} | "
                       f"{_cell(c.info['desc'])} |")
        out.append("")
    out += ["## Lifecycle states and allowed transitions\n",
            "Each change writes an `event` row. Validation (check C6) replays the events and fails on any "
            "transition not listed here.\n", "| Entity | From | Allowed next states |", "|---|---|---|"]
    for entity, table in TRANSITIONS.items():
        for frm, to in table.items():
            out.append(f"| {entity} | {frm or '(creation)'} | {', '.join(sorted(to))} |")
    return "\n".join(out) + "\n"


def erd() -> str:
    lines = ["erDiagram"]
    for name in ORDER:
        t = schema.TABLES[name]
        for fk in sorted(t.foreign_keys, key=lambda f: f.parent.name):
            parent = fk.column.table.name
            if parent == name:
                lines.append(f'    {name} }}o--o| {name} : "{fk.parent.name}"')
                continue
            pk = list(t.primary_key.columns)
            one = fk.parent.unique or (fk.parent in pk and len(pk) == 1)
            left = "|o" if fk.parent.nullable else "||"
            right = "o|" if one else "o{"
            lines.append(f'    {parent} {left}--{right} {name} : "{fk.parent.name}"')
    return (GENERATED + "# Entity relationship diagram\n\nGenerated from the foreign keys in the schema. "
            "`||--o{` reads as one parent to many children; `|o` means the parent is optional.\n\n```mermaid\n"
            + "\n".join(lines) + "\n```\n")


# ------------------------------------------------------------------------------------------- walkthrough
def pick_student(ds: dict, gt: list[dict]) -> str:
    """The first student (by id) whose story shows the most rules at once; students with a label are skipped."""
    labelled = {g["student_id"] for g in gt}
    score = defaultdict(int)
    inv_owner = {i["invoice_id"]: i["student_id"] for i in ds["invoice"]}
    for ln in ds["invoice_line"]:
        sid = inv_owner[ln["invoice_id"]]
        score[(sid, ln["line_type"])] += 1
    for r in ds["refund"]:
        score[(r["student_id"], "REFUND_" + r["reason"])] += 1
    for e in ds["enrollment"]:
        score[(e["student_id"], e["status"])] += 1
    kinds = ("WAIVER", "SCHOLARSHIP", "LATE_FEE", "ADJUSTMENT", "REFUND_WITHDRAWAL", "WITHDRAWN")
    best = max((sid for sid in {s["student_id"] for s in ds["student"]} if sid not in labelled),
               key=lambda sid: (sum(1 for k in kinds if score[(sid, k)]), -ids.student_no(sid)))
    return best


def walkthrough(ds: dict, gt: list[dict], detected: list[dict]) -> str:
    sid = pick_student(ds, gt)
    s = next(x for x in ds["student"] if x["student_id"] == sid)
    prog = next(p for p in ds["program"] if p["program_id"] == s["program_id"])
    out = [GENERATED, f"# Worked example: {sid}\n",
           "One student followed end to end, taken from the starter dataset (seed 20261022). Every number below is "
           "read from the generated rows, and each can be re-derived by the rule named beside it (rule ids refer to "
           "[`architecture.md`](architecture.md)). The student is chosen automatically: the first one without an "
           "injected anomaly whose story touches the most rules.\n",
           "## The student\n",
           f"{s['full_name']}, {prog['name']} ({prog['level']}), {s['residency'].lower()}, GPA {s['gpa']}, "
           f"income band {s['income_band']}, sports quota {'yes' if s['sports_quota'] else 'no'}, hostel "
           f"{'yes' if s['hostel_resident'] else 'no'}, waiver {s['waiver_type'] or 'none'}.\n"]
    invoices = sorted((i for i in ds["invoice"] if i["student_id"] == sid), key=lambda i: i["issue_date"])
    lines_of = defaultdict(list)
    for ln in ds["invoice_line"]:
        lines_of[ln["invoice_id"]].append(ln)
    allocs = defaultdict(list)
    for a in ds["payment_allocation"]:
        allocs[a["invoice_line_id"]].append(a)
    enrollment = {e["enrollment_id"]: e for e in ds["enrollment"]}
    out.append("## Invoices and their lines\n")
    for inv in invoices:
        enr = enrollment[inv["enrollment_id"]]
        left = f", **{enr['status']} on {enr['left_on']}**" if enr["left_on"] else ""
        out += [f"### {inv['invoice_id']} ({inv['term_id']}){left}\n",
                f"Issued {inv['issue_date']}, due {inv['due_date']}, status **{inv['status']}** as of 2026-09-05, "
                f"total **{inr(inv['total_paise'])}**.\n",
                "| Line | Type | Description | Amount | Posted | Paid by allocations |", "|---|---|---|---|---|---|"]
        for ln in lines_of[inv["invoice_id"]]:
            paid = sum(a["amount_paise"] for a in allocs[ln["invoice_line_id"]])
            shown = inr(paid) if ln["line_type"] in billing.CHARGE_TYPES else ""
            out.append(f"| {ln['line_no']} | {ln['line_type']} | {_cell(ln['description'])} | "
                       f"{inr(ln['amount_paise'])} | "
                       f"{ln['posted_on']} | {shown} |")
        out.append("")
    out += ["## Payments and how they were allocated (R-PAY)\n",
            "| Payment | Received | Amount | Method | Allocations (line: amount, date) |", "|---|---|---|---|---|"]
    by_payment = defaultdict(list)
    for a in ds["payment_allocation"]:
        by_payment[a["payment_id"]].append(a)
    pays = sorted((p for p in ds["payment"] if p["student_id"] == sid), key=lambda p: p["payment_id"])
    for p in pays:
        parts = "; ".join(f"{a['invoice_line_id'][-14:]}: {inr(a['amount_paise'])} on {a['allocated_on']}"
                          for a in by_payment[p["payment_id"]])
        out.append(f"| {p['payment_id']} | {p['received_on']} | {inr(p['amount_paise'])} | {p['method']} | "
                   f"{parts or '(unapplied)'} |")
    refunds = sorted((r for r in ds["refund"] if r["student_id"] == sid), key=lambda r: r["refund_id"])
    if refunds:
        out += ["\n## Refunds (R-REF)\n", "| Refund | Reason | Amount | Approved | Paid | Against payment |",
                "|---|---|---|---|---|---|"]
        out += [f"| {r['refund_id']} | {r['reason']} | {inr(r['amount_paise'])} | {r['approved_on']} | "
                f"{r['paid_on'] or 'not yet'} "
                f"| {r['payment_id']} |" for r in refunds]
    entries = sorted((e for e in ds["ledger_entry"] if e["student_id"] == sid), key=lambda e: e["entry_id"])
    out += ["\n## The ledger and the balance (R-LED)\n", "| Entry | Date | Type | Amount | Running balance |",
            "|---|---|---|---|---|"]
    running = 0
    for e in entries:
        running += e["amount_paise"]
        out.append(f"| {e['entry_id']} | {e['posted_on']} | {e['entry_type']} | {inr(e['amount_paise'])} | "
                   f"{inr(running)} |")
    bal = next(b for b in ds["student_balance"] if b["student_id"] == sid)
    totals = sum(i["total_paise"] for i in invoices)
    paid = sum(p["amount_paise"] for p in pays)
    back = sum(r["amount_paise"] for r in refunds)
    agree = bal["balance_paise"] == ledger.balance(entries) == ledger.identity_balance([totals], [paid], [back])
    out += [f"\nStated balance **{inr(bal['balance_paise'])}**; ledger sum **{inr(ledger.balance(entries))}**; "
            f"invoices - payments + refunds = {inr(totals)} - {inr(paid)} + {inr(back)} = "
            f"**{inr(ledger.identity_balance([totals], [paid], [back]))}**. The three routes agree "
            f"({'yes' if agree else 'NO'}).\n"
            "Positive means the student owes money; negative means the institution holds credit.\n"]
    history = [e for e in ds["event"] if e["entity_id"] in {i["invoice_id"] for i in invoices}
               or e["entity_id"] in {e2["enrollment_id"] for e2 in ds["enrollment"] if e2["student_id"] == sid}]
    out += ["## State history (append-only events)\n", "| Date | Entity | From | To |", "|---|---|---|---|"]
    out += [f"| {e['occurred_on']} | {e['entity_id']} | {e['from_status'] or '(created)'} | {e['to_status']} |"
            for e in sorted(history, key=lambda e: (e["occurred_on"], e["event_id"]))]
    out += ["\n## The five labelled anomalies, and how each is found\n",
            "Injected after the clean data, on separate students, and listed only in `ground_truth`. The detector "
            "recomputes each figure from the source rows and never sees the label.\n",
            "| Issue type | Entity | Student | What was done | The correct figure | Detector says |",
            "|---|---|---|---|---|---|"]
    found = {(e["exception_type"], e["entity_id"]): e for e in detected}
    seen = set()
    for g in gt:
        if g["issue_type"] in seen:
            continue
        seen.add(g["issue_type"])
        e = found.get((g["issue_type"], g["entity_id"]))
        verdict = (f"{e['recommended_decision']} (expected {inr(e['expected_paise'] or 0)}, "
                   f"found {inr(e['found_paise'])})" if e else "not found")
        out.append(f"| {g['issue_type']} | {g['entity_type']} `{g['entity_id']}` | {g['student_id']} | "
                   f"{_cell(g['details'])} | {inr(g['expected_value_paise'] or 0)} -> {g['expected_decision']} | "
                   f"{verdict} |")
    return "\n".join(out) + "\n"


def write_all(root: Path = ROOT) -> dict[str, str]:
    from app.datagen import writer
    from app.engine import detect
    ds, gt = writer.read(root / "data" / "starter")
    docs = {"data_dictionary.md": data_dictionary(), "erd.md": erd(),
            "walkthrough.md": walkthrough(ds, gt, detect.run(ds))}
    for name, text in docs.items():
        (root / "docs" / name).write_text(text, encoding="utf-8", newline="\n")
    return docs


def check(root: Path = ROOT) -> list[str]:
    """Names of generated documents whose committed copy differs from a fresh render."""
    from app.datagen import writer
    from app.engine import detect
    ds, gt = writer.read(root / "data" / "starter")
    fresh = {"data_dictionary.md": data_dictionary(), "erd.md": erd(),
             "walkthrough.md": walkthrough(ds, gt, detect.run(ds))}
    return [n for n, text in fresh.items()
            if not (root / "docs" / n).exists() or (root / "docs" / n).read_text(encoding="utf-8") != text]
